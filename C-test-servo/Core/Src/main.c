/*
 * printf 的底层出口。
 * newlib 的 printf 最终会调用 syscalls.c 里的 _write()，
 * 而 _write() 是 weak 的，它逐字节调用 __io_putchar()。
 * 这个函数不定义的话链接不报错，但运行时跳到 0 地址 -> HardFault。
 */
